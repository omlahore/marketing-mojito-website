/**
 * Extracts main content from public/brand-visual-identity.html.bak (section_hero … through
 * last </section> before mobile-dock), fixes asset paths. Writes one full body string
 * for dangerouslySetInnerHTML (no chunk splitting).
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const htmlPath = [path.join(root, 'public', 'brand-visual-identity.html'), path.join(root, 'public', 'brand-visual-identity.html.bak')].find(
  (p) => fs.existsSync(p),
);
if (!htmlPath) throw new Error('Missing public/brand-visual-identity.html or .html.bak');
const outPath = path.join(root, 'app', 'brand-visual-identity', 'bodyChunks.generated.ts');

const lines = fs.readFileSync(htmlPath, 'utf8').split(/\r?\n/);
const slice = lines.slice(954, 2357).join('\n');

function fixPaths(html) {
  return html
    .replace(/\bsrc="images\//g, 'src="/images/')
    .replace(/\bsrcset="images\//g, 'srcset="/images/')
    .replace(/,\s*images\//g, ', /images/')
    .replace(/\bhref="images\//g, 'href="/images/')
    .replace(/\burl\(images\//gi, 'url(/images/');
}

const body = fixPaths(slice);

const esc = (s) => {
  return s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
};

const out = `/* eslint-disable max-lines */
/** Auto-generated by scripts/generate-brand-visual-identity-chunks.mjs — do not edit by hand */
export const brandPageFullBody = \`${esc(body)}\`;
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, out, 'utf8');
console.log('Wrote', outPath);
